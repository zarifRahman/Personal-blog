// One-time: convert the old blog's MDX into a self-contained content module.
// Reads ~/Desktop/zarif-blog/content, copies images, writes src/content/posts/index.js.
//   node scripts/gen-static-posts.mjs
import matter from "gray-matter";
import { marked } from "marked";
import { readFileSync, writeFileSync, readdirSync, copyFileSync, mkdirSync, existsSync } from "node:fs";
import { join, basename } from "node:path";

const SRC = "/Users/shikho/Desktop/zarif-blog";
const CONTENT = join(SRC, "content");
const SRC_IMG = join(SRC, "public", "blogs");
const DEST_IMG = join(process.cwd(), "public", "blogs");
const OUT = join(process.cwd(), "src", "content", "posts", "index.js");

if (!existsSync(DEST_IMG)) mkdirSync(DEST_IMG, { recursive: true });
if (!existsSync(join(process.cwd(), "src", "content", "posts")))
  mkdirSync(join(process.cwd(), "src", "content", "posts"), { recursive: true });

const posts = [];
for (const slug of readdirSync(CONTENT)) {
  const mdx = join(CONTENT, slug, "index.mdx");
  if (!existsSync(mdx)) continue;
  const { data: fm, content } = matter(readFileSync(mdx, "utf8"));

  let img = null;
  if (fm.image) {
    const file = basename(fm.image);
    if (existsSync(join(SRC_IMG, file))) {
      copyFileSync(join(SRC_IMG, file), join(DEST_IMG, file));
      img = `/blogs/${file}`;
    }
  }

  posts.push({
    slug,
    title: fm.title,
    desc: marked.parse(content),
    img,
    catSlug: "coding",
    author: "Zarif Shahriar",
    createdAt: `${fm.publishedAt}T00:00:00.000Z`,
    tags: fm.tags || [],
    views: 40 + (content.length % 460),
  });
}

posts.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));

const file = `// AUTO-GENERATED by scripts/gen-static-posts.mjs — do not edit by hand.
// Static blog posts imported from the old contentlayer repo (no DB needed).
export const posts = ${JSON.stringify(posts, null, 2)};

export const getPost = (slug) => posts.find((p) => p.slug === slug) || null;
`;
writeFileSync(OUT, file);
console.log(`Wrote ${posts.length} posts to ${OUT}`);
